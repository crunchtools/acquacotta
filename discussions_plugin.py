"""Acquacotta Discussions Plugin — conversations to have, organized by person.

A discussion is a conversation Scott wants to have with someone: who it's with, the
topic, context, the talking points to raise, and — after it happens — the outcome. It
started life as a custom list inside Todos ("Person: topic"); this plugin makes it a
first-class record where the person is a real field and there's a place to capture what
was decided.

Mirrors ``todos_plugin`` in structure: a full-document ``plugins/discussions/data.json``
in the user's Drive, read-modify-write CRUD helpers reused by the web UI's
``/api/discussions/sync`` and by the MCP tools below.
"""

import json
import re
import uuid
from datetime import datetime, timezone

import deep_links
from transports.google_drive_transport import GoogleDriveTransport

# Discussion IDs are always UUIDs (generated by the web client and the MCP tools).
# The sync boundary enforces this so a crafted ID can never reach the frontend, where
# IDs are interpolated into HTML attributes and inline handlers.
_UUID_RE = re.compile(r"\A[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\Z")

PLUGIN_METADATA = {
    "id": "discussions",
    "name": "Discussions",
    "description": "Conversations to have, organized by person, with talking points and outcomes",
    "version": "1.0.0",
    "type": "extension",
    "author": "Crunchtools",
    "has_tab": True,
    "tab_label": "Discussions",
    "tab_id": "discussions",
    "has_counts": True,
    "has_sync": True,
    "has_import_export": True,
}

DISCUSSIONS_FILE = "data.json"
PLUGIN_FOLDER = "plugins/discussions"


def _empty_doc():
    """A fresh empty document. Never share one instance: callers mutate the inner
    ``discussions`` list in place, so a shared dict would leak records across calls
    (and, on the server, across users)."""
    return {"discussions": []}


def _transport(drive_service, folder_id):
    return GoogleDriveTransport(drive_service, folder_id)


def _ensure_plugin_folder(t, folder_id):
    """Ensure plugins/discussions/ subfolder exists, return its folder ID."""
    service = t._service
    plugins_id = _find_or_create_folder(service, folder_id, "plugins")
    return _find_or_create_folder(service, plugins_id, "discussions")


def _find_or_create_folder(service, parent_id, name):
    query = (
        f"name='{name}' and '{parent_id}' in parents "
        f"and mimeType='application/vnd.google-apps.folder' and trashed=false"
    )
    results = service.files().list(q=query, spaces="drive", fields="files(id)").execute()
    files = results.get("files", [])
    if files:
        return files[0]["id"]
    metadata = {
        "name": name,
        "mimeType": "application/vnd.google-apps.folder",
        "parents": [parent_id],
    }
    folder = service.files().create(body=metadata, fields="id").execute()
    return folder["id"]


def read_discussions(drive_service, folder_id):
    """Read the user's discussions document from their Google Drive.

    Args:
        drive_service: An authenticated Google Drive v3 service for this user.
        folder_id: The user's Acquacotta root folder ID; the document lives at
            ``plugins/discussions/data.json`` beneath it (created on demand).

    Returns:
        The document as ``{"discussions": [<record>, ...]}``, with any record that
        fails ``_validate_record`` (e.g. a non-UUID id in a hand-edited file)
        dropped. If the file is missing, empty, or malformed JSON, returns a fresh
        ``{"discussions": []}`` rather than raising, so first-run and corrupted
        states degrade gracefully.
    """
    t = _transport(drive_service, folder_id)
    disc_folder_id = _ensure_plugin_folder(t, folder_id)
    disc_transport = GoogleDriveTransport(drive_service, disc_folder_id)
    content = disc_transport.download_file(DISCUSSIONS_FILE)
    if content is None:
        return _empty_doc()
    try:
        discussions_data = json.loads(content)
        if not isinstance(discussions_data, dict):
            return _empty_doc()
        # The Drive file is user-editable out of band; drop any record that isn't
        # safe to render (see _safe_records) before returning it to the API/UI.
        discussions_data["discussions"] = _safe_records(discussions_data.get("discussions", []))
        return discussions_data
    except (json.JSONDecodeError, TypeError):
        return _empty_doc()


def write_discussions(drive_service, folder_id, discussions_data):
    """Persist the user's discussions document to their Google Drive (full replace).

    Args:
        drive_service: An authenticated Google Drive v3 service for this user.
        folder_id: The user's Acquacotta root folder ID; the document is written to
            ``plugins/discussions/data.json`` beneath it (folder created on demand).
        discussions_data: The complete document to store, ``{"discussions": [...]}``.
            This replaces whatever is currently stored (no merge). Callers that
            accept untrusted input should pass it through ``validate_sync_payload``
            first. Serialized as pretty-printed UTF-8 JSON.

    Raises:
        googleapiclient.errors.HttpError: if the Drive write fails.
    """
    t = _transport(drive_service, folder_id)
    disc_folder_id = _ensure_plugin_folder(t, folder_id)
    disc_transport = GoogleDriveTransport(drive_service, disc_folder_id)
    content = json.dumps(discussions_data, indent=2, ensure_ascii=False)
    disc_transport.upload_file(DISCUSSIONS_FILE, content)


# Agent-facing CRUD helpers (used by the MCP tools below and the web UI). These read the
# whole discussions document, mutate it, and write it back — the same full-replace
# contract the web UI's /api/discussions/sync uses. Record shapes mirror
# static/js/storage.js exactly so agent-created records are indistinguishable from
# UI-created ones.

_VALID_PRIORITIES = ("none", "low", "medium", "high")
_VALID_STATUSES = ("open", "discussed")
_UNSORTED_LAST = 999999  # discussions lacking a sort_order sort after those that have one


def validate_sync_payload(payload):
    """Validate a full-replace sync payload from the web client and return a clean
    ``{"discussions": [...]}`` document. Raises ValueError on a malformed shape.

    The web UI owns the document (same full-replace contract as Todos), but the
    endpoint is still a state-changing API, so we check the structure and every
    record (see ``_validate_record``) before writing anything to the user's Drive.
    """
    if not isinstance(payload, dict):
        raise ValueError("payload must be an object")
    records = payload.get("discussions", [])
    if not isinstance(records, list):
        raise ValueError("'discussions' must be a list")
    for record in records:
        _validate_record(record)
    return {"discussions": records}


def _validate_record(record):
    """Raise ValueError unless ``record`` is a safe-to-render discussion.

    The checks are the trust boundary for the frontend, which interpolates the id
    into an inline handler/attribute and other fields into HTML. Enforced here for
    both the write path (``validate_sync_payload``) and the read path
    (``_safe_records``), since the Drive document is user-editable out of band.
    """
    if not isinstance(record, dict):
        raise ValueError("each discussion must be an object")
    record_id = record.get("id")
    if not isinstance(record_id, str) or not _UUID_RE.match(record_id):
        raise ValueError("each discussion must have a UUID id")
    priority = record.get("priority")
    if priority is not None and priority not in _VALID_PRIORITIES:
        raise ValueError(f"priority must be one of {_VALID_PRIORITIES}")
    status = record.get("status")
    if status is not None and status not in _VALID_STATUSES:
        raise ValueError(f"status must be one of {_VALID_STATUSES}")
    points = record.get("talking_points")
    if points is not None and not isinstance(points, list):
        raise ValueError("talking_points must be a list")
    # Text fields are consumed as strings by the UI (e.g. person.trim()), so a
    # non-string value would break rendering — reject it at the boundary.
    for field in ("person", "topic", "context", "outcome", "source", "due_date"):
        value = record.get(field)
        if value is not None and not isinstance(value, str):
            raise ValueError(f"{field} must be a string")


def _safe_records(records):
    """Return only the records that pass ``_validate_record``.

    Used on read: a hand-edited Drive file can contain anything, so a record that
    would be unsafe to render (e.g. a non-UUID id that could break out of an inline
    handler) is dropped rather than returned to the API or the UI.
    """
    if not isinstance(records, list):
        return []
    safe = []
    for record in records:
        try:
            _validate_record(record)
        except ValueError:
            continue
        safe.append(record)
    return safe


def _now_iso():
    return datetime.now(timezone.utc).isoformat()


def _normalize_talking_points(talking_points):
    """Coerce talking points into a clean list[str]. Accepts a list or a newline string."""
    if talking_points is None:
        return []
    if isinstance(talking_points, str):
        items = talking_points.splitlines()
    else:
        items = list(talking_points)
    return [str(p).strip() for p in items if str(p).strip()]


def query_discussions(drive_service, folder_id, status=None, person=None, priority=None, q=None):
    """Return the user's discussions, optionally filtered, sorted open-first.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        status: keep only this status — ``"open"`` or ``"discussed"``. None = any.
        person: keep only discussions with this person (exact match, trimmed,
            case-insensitive). None = any.
        priority: keep only this priority — one of ``"none"``, ``"low"``,
            ``"medium"``, ``"high"``. None = any. A different value raises ValueError.
        q: keep only discussions whose topic, context, or any talking point contains
            this substring (case-insensitive). None/empty = no text filter.

    Returns:
        A list of discussion records (the dict shape produced by ``add_discussion``),
        ordered open records first, then by ``sort_order`` ascending.

    Raises:
        ValueError: if ``priority`` is not a recognized value.
    """
    if priority is not None and priority not in _VALID_PRIORITIES:
        raise ValueError(f"priority must be one of {_VALID_PRIORITIES}")
    doc = read_discussions(drive_service, folder_id)
    discussions = doc.get("discussions", [])
    if status:
        discussions = [d for d in discussions if d.get("status") == status]
    if person is not None:
        needle = person.strip().lower()
        discussions = [d for d in discussions if (d.get("person") or "").strip().lower() == needle]
    if priority is not None:
        discussions = [d for d in discussions if d.get("priority") == priority]
    if q:
        needle = q.lower()
        discussions = [
            d
            for d in discussions
            if needle in (d.get("topic") or "").lower()
            or needle in (d.get("context") or "").lower()
            or any(needle in str(p).lower() for p in (d.get("talking_points") or []))
        ]
    discussions = sorted(
        discussions,
        key=lambda d: (d.get("status") != "open", d.get("sort_order", _UNSORTED_LAST)),
    )
    return discussions


def add_discussion(
    drive_service,
    folder_id,
    topic,
    person="",
    context="",
    talking_points=None,
    priority="none",
    due_date=None,
    source="",
):
    """Create a discussion, persist the whole document, and return the new record.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        topic: what to discuss (required; non-blank after trimming, else ValueError).
        person: who the discussion is with (free text, trimmed; default "").
        context: background for the conversation (default "").
        talking_points: points/asks/questions to raise — a list, or a newline-
            delimited string; either is normalized to a clean list[str].
        priority: one of ``"none"``, ``"low"``, ``"medium"``, ``"high"`` (default
            ``"none"``); any other value raises ValueError.
        due_date: optional ISO date (YYYY-MM-DD) to have the conversation by.
        source: optional reference, e.g. a Slack/email thread URL (trimmed).

    Returns:
        The created record: ``id`` (UUID), ``person``, ``topic``, ``context``,
        ``talking_points`` (list), ``status`` ("open"), ``priority``, ``outcome``
        (""), ``source``, ``due_date``, ``sort_order`` (max existing + 1),
        ``created_at`` (ISO), ``discussed_at`` (None).

    Raises:
        ValueError: on a blank topic or an invalid priority.
    """
    if not topic or not topic.strip():
        raise ValueError("topic is required")
    if priority not in _VALID_PRIORITIES:
        raise ValueError(f"priority must be one of {_VALID_PRIORITIES}")
    doc = read_discussions(drive_service, folder_id)
    discussions = doc.setdefault("discussions", [])
    max_order = max((d.get("sort_order", 0) for d in discussions), default=0)
    discussion = {
        "id": str(uuid.uuid4()),
        "person": (person or "").strip(),
        "topic": topic.strip(),
        "context": context or "",
        "talking_points": _normalize_talking_points(talking_points),
        "status": "open",
        "priority": priority,
        "outcome": "",
        "source": (source or "").strip(),
        "due_date": due_date,
        "sort_order": max_order + 1,
        "created_at": _now_iso(),
        "discussed_at": None,
    }
    discussions.append(discussion)
    write_discussions(drive_service, folder_id, doc)
    return discussion


def set_discussion_status(drive_service, folder_id, discussion_id, status, outcome=None):
    """Set a discussion's status, persist the document, and return the record.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        discussion_id: the UUID of the discussion to update.
        status: ``"discussed"`` or ``"open"``; any other value raises ValueError.
        outcome: optional text recorded only when marking ``"discussed"``.

    Behavior:
        Marking ``"discussed"`` stamps ``discussed_at`` (now) and, if ``outcome`` is
        given, stores it. Reopening (``"open"``) clears ``discussed_at`` but leaves
        any previously recorded outcome in place.

    Returns:
        The updated record, or ``None`` if no discussion has that id.

    Raises:
        ValueError: if ``status`` is not ``"open"`` or ``"discussed"``.
    """
    if status not in ("open", "discussed"):
        raise ValueError("status must be 'open' or 'discussed'")
    doc = read_discussions(drive_service, folder_id)
    for discussion in doc.get("discussions", []):
        if discussion.get("id") == discussion_id:
            discussion["status"] = status
            discussion["discussed_at"] = _now_iso() if status == "discussed" else None
            if status == "discussed" and outcome is not None:
                discussion["outcome"] = outcome
            write_discussions(drive_service, folder_id, doc)
            return discussion
    return None


def modify_discussion(drive_service, folder_id, discussion_id, fields):
    """Update selected fields on one discussion and persist the document.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        discussion_id: the UUID of the discussion to update.
        fields: a mapping of changes. Only these keys are applied — ``person``,
            ``topic``, ``context``, ``talking_points``, ``priority``, ``due_date``,
            ``outcome``, ``source``; any other key is ignored. A key whose value is
            ``None`` is treated as "no change" and skipped (so partial updates are
            safe). ``priority`` must be a valid value or ValueError is raised;
            ``talking_points`` is normalized to a clean list[str].

    Returns:
        The updated record, or ``None`` if no discussion has that id.

    Raises:
        ValueError: if ``priority`` is present and not a recognized value.
    """
    allowed = {"person", "topic", "context", "talking_points", "priority", "due_date", "outcome", "source"}
    updates = {k: v for k, v in fields.items() if k in allowed and v is not None}
    if "priority" in updates and updates["priority"] not in _VALID_PRIORITIES:
        raise ValueError(f"priority must be one of {_VALID_PRIORITIES}")
    if "talking_points" in updates:
        updates["talking_points"] = _normalize_talking_points(updates["talking_points"])
    doc = read_discussions(drive_service, folder_id)
    for discussion in doc.get("discussions", []):
        if discussion.get("id") == discussion_id:
            discussion.update(updates)
            write_discussions(drive_service, folder_id, doc)
            return discussion
    return None


def remove_discussion(drive_service, folder_id, discussion_id):
    """Permanently remove one discussion and persist the document.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        discussion_id: the UUID of the discussion to delete.

    Returns:
        True if a discussion with that id existed and was removed, False otherwise.
    """
    doc = read_discussions(drive_service, folder_id)
    discussions = doc.get("discussions", [])
    remaining = [d for d in discussions if d.get("id") != discussion_id]
    if len(remaining) == len(discussions):
        return False
    doc["discussions"] = remaining
    write_discussions(drive_service, folder_id, doc)
    return True


def set_discussion_order(drive_service, folder_id, discussion_id, sort_order):
    """Set a discussion's sort_order (its position in the list) and persist it.

    Args:
        drive_service, folder_id: see ``read_discussions``.
        discussion_id: the UUID of the discussion to move.
        sort_order: the new integer position (lower sorts earlier); a non-int
            raises ValueError.

    Returns:
        The updated record, or ``None`` if no discussion has that id.

    Raises:
        ValueError: if ``sort_order`` is not an int.
    """
    if not isinstance(sort_order, int):
        raise ValueError("sort_order must be an integer")
    doc = read_discussions(drive_service, folder_id)
    for discussion in doc.get("discussions", []):
        if discussion.get("id") == discussion_id:
            discussion["sort_order"] = sort_order
            write_discussions(drive_service, folder_id, doc)
            return discussion
    return None


def register_mcp_tools(mcp, require_ctx):
    """Register this plugin's MCP tools on a FastMCP instance.

    Called once at startup by the MCP server (via the plugin registry). Defines and
    registers the discussion tools (list/create/mark_discussed/update/delete/reorder)
    as side effects on ``mcp``; returns nothing.

    Args:
        mcp: the FastMCP instance to register the ``@mcp.tool()`` functions on.
        require_ctx: a zero-arg callable the server supplies that authenticates the
            current request and returns the per-request context
            ``{"service", "folder_id", "email"}`` (raising on an invalid token).

    Returns:
        None.
    """
    from fastmcp.exceptions import ToolError

    @mcp.tool()
    def list_discussions(
        status: str | None = None,
        person: str | None = None,
        priority: str | None = None,
        q: str | None = None,
    ) -> list:
        """List the user's discussions (conversations to have, organized by person).

        Args:
            status: Optional filter — 'open' or 'discussed'.
            person: Optional filter — only discussions with this person (exact, case-insensitive).
            priority: Optional filter — 'none', 'low', 'medium', or 'high'.
            q: Optional text search — matches topic, context, and talking points.

        Returns:
            A list of discussion records, ordered open-first then by sort_order. Each
            record has: id, person, topic, context, talking_points (list), status
            ('open'|'discussed'), priority, outcome, source, due_date, sort_order,
            created_at, discussed_at, and link (a URL that opens it in Acquacotta,
            when the server knows its public URL). Raises a tool error if priority
            is invalid.
        """
        ctx = require_ctx()
        try:
            discussions = query_discussions(
                ctx["service"], ctx["folder_id"], status=status, person=person, priority=priority, q=q
            )
            return deep_links.with_links(discussions, "discussions", "item")
        except ValueError as exc:
            raise ToolError(str(exc)) from exc

    @mcp.tool()
    def create_discussion(
        topic: str,
        person: str = "",
        context: str = "",
        talking_points: list[str] | None = None,
        priority: str = "none",
        due_date: str | None = None,
        source: str = "",
    ) -> dict:
        """Create a new discussion.

        Args:
            topic: What to discuss (required).
            person: Who the discussion is with.
            context: Background for the conversation.
            talking_points: The specific points/asks/questions to raise.
            priority: 'none', 'low', 'medium', or 'high'.
            due_date: Optional ISO date (YYYY-MM-DD) to have the conversation by.
            source: Optional reference (e.g. a Slack/email thread URL).

        Returns:
            The created discussion record (see list_discussions for its fields).
            Raises a tool error on a blank topic or invalid priority.
        """
        ctx = require_ctx()
        try:
            discussion = add_discussion(
                ctx["service"],
                ctx["folder_id"],
                topic,
                person=person,
                context=context,
                talking_points=talking_points,
                priority=priority,
                due_date=due_date,
                source=source,
            )
            return deep_links.with_link(discussion, "discussions", "item")
        except ValueError as exc:
            raise ToolError(str(exc)) from exc

    @mcp.tool()
    def mark_discussed(discussion_id: str, outcome: str = "") -> dict:
        """Mark a discussion as discussed, optionally recording the outcome.

        Args:
            discussion_id: The id of the discussion.
            outcome: What was decided or what came out of the conversation.

        Returns:
            The updated discussion record (status 'discussed', discussed_at stamped).
            Raises a tool error if no discussion has that id.
        """
        ctx = require_ctx()
        updated = set_discussion_status(ctx["service"], ctx["folder_id"], discussion_id, "discussed", outcome)
        if updated is None:
            raise ToolError(f"No discussion found with id {discussion_id}")
        return deep_links.with_link(updated, "discussions", "item")

    @mcp.tool()
    def update_discussion(
        discussion_id: str,
        person: str | None = None,
        topic: str | None = None,
        context: str | None = None,
        talking_points: list[str] | None = None,
        priority: str | None = None,
        due_date: str | None = None,
        outcome: str | None = None,
        source: str | None = None,
    ) -> dict:
        """Update fields on an existing discussion. Only provided fields change.

        Args:
            discussion_id: The id of the discussion to update.
            person: Who the discussion is with.
            topic: What to discuss.
            context: Background.
            talking_points: The points/asks/questions to raise.
            priority: 'none', 'low', 'medium', or 'high'.
            due_date: ISO due date.
            outcome: What was decided.
            source: Reference URL.

        Returns:
            The updated discussion record. Only provided (non-None) fields change.
            Raises a tool error on invalid priority or if no discussion has that id.
        """
        ctx = require_ctx()
        fields = {
            "person": person,
            "topic": topic,
            "context": context,
            "talking_points": talking_points,
            "priority": priority,
            "due_date": due_date,
            "outcome": outcome,
            "source": source,
        }
        try:
            updated = modify_discussion(ctx["service"], ctx["folder_id"], discussion_id, fields)
        except ValueError as exc:
            raise ToolError(str(exc)) from exc
        if updated is None:
            raise ToolError(f"No discussion found with id {discussion_id}")
        return deep_links.with_link(updated, "discussions", "item")

    @mcp.tool()
    def delete_discussion(discussion_id: str) -> dict:
        """Permanently delete a discussion (distinct from mark_discussed, which resolves it).

        Args:
            discussion_id: The id of the discussion to delete.

        Returns:
            ``{"status": "ok", "deleted": <id>}``. Raises a tool error if no
            discussion has that id.
        """
        ctx = require_ctx()
        if not remove_discussion(ctx["service"], ctx["folder_id"], discussion_id):
            raise ToolError(f"No discussion found with id {discussion_id}")
        return {"status": "ok", "deleted": discussion_id}

    @mcp.tool()
    def reorder_discussion(discussion_id: str, sort_order: int) -> dict:
        """Change a discussion's sort position without touching its other fields.

        Args:
            discussion_id: The id of the discussion to move.
            sort_order: The new sort_order (lower sorts earlier).

        Returns:
            The updated discussion record. Raises a tool error on a non-integer
            sort_order or if no discussion has that id.
        """
        ctx = require_ctx()
        try:
            moved = set_discussion_order(ctx["service"], ctx["folder_id"], discussion_id, sort_order)
        except ValueError as exc:
            raise ToolError(str(exc)) from exc
        if moved is None:
            raise ToolError(f"No discussion found with id {discussion_id}")
        return moved
